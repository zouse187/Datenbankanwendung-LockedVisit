CREATE TABLE GEFANGENEN_TERMINE (
    GEFANGENER_ID NUMBER,
    BESUCHER_ID   NUMBER DEFAULT NULL, -- NULL erlaubt, solange der Termin frei (0) ist
    DATUM         DATE,
    GEBUCHT       NUMBER(1) DEFAULT 0, -- 0 = Frei, 1 = Gebucht

    -- Zusammengesetzter Primärschlüssel: Verhindert, dass ein Gefangener doppelt zur exakt selben Zeit eingetragen wird
    CONSTRAINT PK_GEFANGENEN_TERMINE PRIMARY KEY (GEFANGENER_ID, DATUM),

    -- Fremdschlüssel-Beziehungen
    CONSTRAINT FK_GT_GEFANGENER FOREIGN KEY (GEFANGENER_ID) 
        REFERENCES GEFANGENER(GEFANGENER_ID) ON DELETE CASCADE,
        
    CONSTRAINT FK_GT_BESUCHER FOREIGN KEY (BESUCHER_ID) 
        REFERENCES BESUCHER(BESUCHER_ID) ON DELETE SET NULL,

    -- Check-Constraint: Erlaubt nur die Werte 0 und 1 in der Spalte GEBUCHT
    CONSTRAINT CHK_GEBUCHT_0_OR_1 CHECK (GEBUCHT IN (0, 1))
);


